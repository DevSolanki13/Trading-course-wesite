"use client";
import { useEffect, useState } from "react";
import { adminApi, operation } from "../../lib/admin-api";
import type { SiteDocument } from "../../../shared/admin";
const initial: SiteDocument = {
  instructorName: "",
  instructorBio: "",
  instructorPortraitUrl: "",
  instructorConfirmed: false,
  heroTitle: "",
  heroAccent: "",
  heroDescription: "",
  teachingTitle: "",
  teachingDescription: "",
  faqs: [],
  testimonials: [],
  genuineTestimonialsConfirmed: false,
};
export function ContentPanel() {
  const [document, setDocument] = useState<SiteDocument>(initial);
  const [version, setVersion] = useState(1);
  const [error, setError] = useState("");
  const [message, setMessage] = useState("");
  const [pending, setPending] = useState(false);
  useEffect(() => {
    adminApi<{ document: Partial<SiteDocument>; version: number }>("content")
      .then((d) => {
        setVersion(d.version);
        setDocument({ ...initial, ...d.document });
      })
      .catch((e) => setError(e.message));
  }, []);
  async function save(e: React.FormEvent) {
    e.preventDefault();
    setPending(true);
    setError("");
    setMessage("");
    try {
      await operation("content", { version, document });
      setVersion((v) => v + 1);
      setMessage("Site copy saved and published. Review the public page for accuracy.");
    } catch (reason) {
      setError(reason instanceof Error ? reason.message : "Content could not save.");
    } finally {
      setPending(false);
    }
  }
  return (
    <section>
      <div className="admin-section-head">
        <div>
          <h2>Website content</h2>
          <p>Keep public copy factual. Empty fields retain the existing preview wording.</p>
        </div>
      </div>
      {error && (
        <p role="alert" className="auth-error">
          {error}
        </p>
      )}
      {message && (
        <p role="status" className="auth-message">
          {message}
        </p>
      )}
      <form className="admin-form" onSubmit={save}>
        <section className="admin-panel">
          <h3>Landing page</h3>
          <div className="admin-form-grid">
            <label>
              Hero first line
              <input
                maxLength={100}
                value={document.heroTitle}
                onChange={(e) => setDocument((d) => ({ ...d, heroTitle: e.target.value }))}
              />
            </label>
            <label>
              Hero highlighted line
              <input
                maxLength={100}
                value={document.heroAccent}
                onChange={(e) => setDocument((d) => ({ ...d, heroAccent: e.target.value }))}
              />
            </label>
          </div>
          <label>
            Hero description
            <textarea
              rows={3}
              maxLength={500}
              value={document.heroDescription}
              onChange={(e) => setDocument((d) => ({ ...d, heroDescription: e.target.value }))}
            />
          </label>
          <label>
            Teaching heading
            <input
              maxLength={140}
              value={document.teachingTitle}
              onChange={(e) => setDocument((d) => ({ ...d, teachingTitle: e.target.value }))}
            />
          </label>
          <label>
            Teaching description
            <textarea
              rows={3}
              maxLength={1000}
              value={document.teachingDescription}
              onChange={(e) => setDocument((d) => ({ ...d, teachingDescription: e.target.value }))}
            />
          </label>
        </section>
        <section className="admin-panel admin-form">
          <h3>Instructor information</h3>
          <p className="admin-help">
            Leave this blank until the real instructor approves their identity, experience and
            image. No credentials are generated by the site.
          </p>
          <label>
            Instructor name
            <input
              value={document.instructorName}
              maxLength={100}
              onChange={(e) => setDocument((d) => ({ ...d, instructorName: e.target.value }))}
            />
          </label>
          <label>
            Verified biography
            <textarea
              value={document.instructorBio}
              maxLength={1200}
              rows={5}
              onChange={(e) => setDocument((d) => ({ ...d, instructorBio: e.target.value }))}
            />
          </label>
          <label>
            Portrait HTTPS URL (optional)
            <input
              type="url"
              value={document.instructorPortraitUrl}
              onChange={(e) =>
                setDocument((d) => ({ ...d, instructorPortraitUrl: e.target.value }))
              }
            />
          </label>
          <label className="admin-checkbox">
            <input
              type="checkbox"
              checked={document.instructorConfirmed}
              onChange={(e) =>
                setDocument((d) => ({ ...d, instructorConfirmed: e.target.checked }))
              }
            />{" "}
            I have verified the biography and have permission to use the portrait
          </label>
        </section>
        <section className="admin-panel">
          <div className="admin-section-head">
            <h3>FAQs</h3>
            <button
              type="button"
              className="button button-secondary"
              disabled={document.faqs.length >= 12}
              onClick={() =>
                setDocument((d) => ({ ...d, faqs: [...d.faqs, { question: "", answer: "" }] }))
              }
            >
              Add FAQ
            </button>
          </div>
          {document.faqs.map((faq, i) => (
            <div key={i} className="admin-resource">
              <label>
                Question
                <input
                  required
                  minLength={3}
                  maxLength={180}
                  value={faq.question}
                  onChange={(e) =>
                    setDocument((d) => ({
                      ...d,
                      faqs: d.faqs.map((x, n) =>
                        n === i ? { ...x, question: e.target.value } : x,
                      ),
                    }))
                  }
                />
              </label>
              <label>
                Answer
                <textarea
                  required
                  minLength={3}
                  maxLength={800}
                  rows={3}
                  value={faq.answer}
                  onChange={(e) =>
                    setDocument((d) => ({
                      ...d,
                      faqs: d.faqs.map((x, n) => (n === i ? { ...x, answer: e.target.value } : x)),
                    }))
                  }
                />
              </label>
              <button
                type="button"
                className="text-link"
                onClick={() =>
                  setDocument((d) => ({ ...d, faqs: d.faqs.filter((_, n) => n !== i) }))
                }
              >
                Remove FAQ
              </button>
            </div>
          ))}
          {!document.faqs.length && (
            <p>The existing preview FAQs remain visible until you add approved replacements.</p>
          )}
        </section>
        <section className="admin-panel">
          <div className="admin-section-head">
            <h3>Verified learner quotes</h3>
            <button
              type="button"
              className="button button-secondary"
              disabled={document.testimonials.length >= 5}
              onClick={() =>
                setDocument((d) => ({
                  ...d,
                  testimonials: [...d.testimonials, { name: "", quote: "", course: "" }],
                }))
              }
            >
              Add quote
            </button>
          </div>
          <p className="admin-help">
            Add only genuine reviews used with the learner&apos;s permission. No review or result is
            generated automatically.
          </p>
          {document.testimonials.map((item, i) => (
            <div key={i} className="admin-resource">
              <div className="admin-form-grid">
                <label>
                  Display name
                  <input
                    value={item.name}
                    minLength={1}
                    maxLength={80}
                    required
                    onChange={(e) =>
                      setDocument((d) => ({
                        ...d,
                        testimonials: d.testimonials.map((x, n) =>
                          n === i ? { ...x, name: e.target.value } : x,
                        ),
                      }))
                    }
                  />
                </label>
                <label>
                  Course label
                  <input
                    value={item.course}
                    maxLength={100}
                    onChange={(e) =>
                      setDocument((d) => ({
                        ...d,
                        testimonials: d.testimonials.map((x, n) =>
                          n === i ? { ...x, course: e.target.value } : x,
                        ),
                      }))
                    }
                  />
                </label>
              </div>
              <label>
                Exact approved quote
                <textarea
                  value={item.quote}
                  minLength={5}
                  maxLength={500}
                  required
                  rows={3}
                  onChange={(e) =>
                    setDocument((d) => ({
                      ...d,
                      testimonials: d.testimonials.map((x, n) =>
                        n === i ? { ...x, quote: e.target.value } : x,
                      ),
                    }))
                  }
                />
              </label>
              <button
                type="button"
                className="text-link"
                onClick={() =>
                  setDocument((d) => ({
                    ...d,
                    testimonials: d.testimonials.filter((_, n) => n !== i),
                  }))
                }
              >
                Remove quote
              </button>
            </div>
          ))}
          <label className="admin-checkbox">
            <input
              type="checkbox"
              checked={document.genuineTestimonialsConfirmed}
              onChange={(e) =>
                setDocument((d) => ({ ...d, genuineTestimonialsConfirmed: e.target.checked }))
              }
            />{" "}
            I confirm all quotes are authentic and approved for publication
          </label>
        </section>
        <button className="button button-primary" disabled={pending}>
          Publish content changes
        </button>
      </form>
    </section>
  );
}
